# encoding=utf-8

import random

# ==========================================
# 1. 准备语料库 (Corpus)
# 这些句子就是你的 AI 目前拥有的所有“世界知识”。
# 它只能基于这些句子的规律来模仿说话。
# ==========================================
corpus = [
    "我喜欢学习", "我会跑步", "我想吃苹果",
    "你喜欢做题", "你想吃草莓", "你会打羽毛球",
    "他喜欢读书", "他会游泳","他想吃香蕉",
    "她喜欢上课","她会打乒乓球","她想喝牛奶",
    "我们喜欢背单词", "我们想吃葡萄", "我们会踢足球",
    "大家喜欢写字", "大家会打篮球", "大家想吃西瓜",
    "哥哥会爬山","哥哥想喝可乐",
    "姐姐会骑车","姐姐想喝茶",
    "朋友喜欢听讲","朋友会滑冰","朋友想喝咖啡",
    "同学会滑雪", "同学想喝果汁",
    "老师喜欢考试",
    "学生喜欢提问",
    "孩子喜欢进步"
]

# ==========================================
# 2. 初始配置 (Prompt & 生成长度)
# ==========================================
prefix = "我"  # 相当于给 AI 的 Prompt（提示词），告诉它以什么字开头
n = 3          # 规定 AI 往后连续生成 3 个字

text = prefix  # text 变量用来存放最终生成的完整句子，初始状态就是 "我"

# ==========================================
# 3. 核心生成逻辑：自回归（逐字生成）
# 循环 n 次，每次只找出一个最合适的“下一个字”
# ==========================================
for _ in range(n):
    opts = []  # 候选池：用来收集所有合法的“下一个字”
    
    # 步骤 A：去语料库里翻书（遍历每一句话）
    for s in corpus:
        # 步骤 B：在当前这句话中，滑动寻找匹配的片段
        # len(s) - len(text) 是为了防止索引越界。
        # 比如句子长 5，当前 text 长 2，那搜索起点最多只能到位置 3。
        for i in range(len(s) - len(text)):
            
            # 步骤 C：核心匹配逻辑
            # 如果从句子 s 的第 i 个位置开始，截取跟当前 text 一样长的片段，
            # 发现刚好和当前的 text 一模一样，说明我们找到了上下文规律！
            if s[i:i+len(text)] == text:
                
                # 步骤 D：收集“下一个字”
                # 把紧跟在这个匹配片段后面的那一个字 s[i+len(text)] 提取出来，扔进候选池
                opts.append(s[i+len(text)])
                
    # 如果遍历完整个语料库，一个候选字都没找到（比如当前生成的词太罕见，或者已经到了句尾）
    # 就必须提前打断循环，强行结束生成
    if not opts: 
        break
        
    # 步骤 E：抽卡（采样）
    # 从候选池中随机抽取一个字，拼接到当前的 text 后面。
    # 随着拼接，text 会越来越长（比如："我" -> "我喜" -> "我喜欢"）
    text += random.choice(opts)

# ==========================================
# 4. 输出最终结果
# ==========================================
print(text)